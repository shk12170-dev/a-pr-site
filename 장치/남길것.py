#!/usr/bin/env python3
"""과제 카드 1~5의 '남길 것'을 남길것/ 폴더에 번호순 파일로 모은다.

build.py와 같은 데이터(본문/, 장치/입력/, 장치/승인문장/, 장치/마지막결과/)만 읽는다.
첫 화면 스크린샷(03_첫화면_PC.png)은 사람이 찍어 넣는 파일이라 이 스크립트가 만들거나 지우지 않는다.

사용법:  python build.py → node 문서_docx.js → python 묶기.py → python 남길것.py
"""

from __future__ import annotations

import json
import re
import shutil
import unicodedata
from pathlib import Path

장치 = Path(__file__).resolve().parent
사업장 = 장치.parent
본문폴더 = 사업장 / "본문"
출력 = 사업장 / "남길것"
능력순서 = ["자기조절력", "대인관계력", "자기동기력"]


def 읽기(경로: Path):
    return json.loads(경로.read_text(encoding="utf-8"))


def 쓰기(이름: str, 줄들: list[str]):
    (출력 / 이름).write_text("\n".join(줄들).rstrip() + "\n", encoding="utf-8")
    print(f"[완료] 남길것/{이름}")


def 본문문단() -> list[str]:
    원문 = (본문폴더 / "자기소개_본문.md").read_text(encoding="utf-8")
    몸통 = 원문.split("---", 1)[1]
    return [p.strip() for p in re.split(r"\n\s*\n", 몸통) if p.strip()]


def 인용_위치(인용: str, 문단들: list[str]) -> str:
    """인용문의 연속된 세 어절이 들어 있는 토막을 찾는다. 날짜만으로 찾으면 같은 날짜의 다른 인용에 걸린다."""
    어절 = 인용.split()
    묶음 = [" ".join(어절[i : i + 3]) for i in range(max(1, len(어절) - 2))]
    for 번호, 문단 in enumerate(문단들, 1):
        if any(조각 in 문단 for 조각 in 묶음):
            return f"{번호}번째 토막"
    return "사이트 '세 가지 능력' 칸에만 있음"


def 만들기():
    설정 = 읽기(본문폴더 / "사이트설정.json")
    트랙 = 설정["트랙"]
    메타 = 읽기(본문폴더 / {"backend": "트랙_백엔드.json", "cloud": "트랙_클라우드.json"}[트랙])
    꼬리 = {"backend": "백엔드", "cloud": "클라우드"}[트랙]
    사이트폴더 = {"backend": "site-backend", "cloud": "site-cloud"}[트랙]
    주소 = 설정.get("배포주소", "").strip() or "(배포 전)"
    문단들 = 본문문단()
    장면들 = [s for s in 읽기(장치 / "승인문장" / "능력별_장면.json")["장면"] if s.get("승인")]
    숫자 = 읽기(장치 / "마지막결과" / "숫자.json")["숫자"]
    판단 = 읽기(본문폴더 / "AI와_나의_판단.json")
    출력.mkdir(exist_ok=True)

    # 01 자기소개 본편
    전체 = "\n\n".join(문단들)
    nfc = unicodedata.normalize("NFC", 전체)
    쓰기("01_자기소개_본편.md", [
        "# 01. 자기소개 본편 (1,500자 안팎)",
        "",
        f"- 분량: 공백 포함 {len(nfc):,}자 · 공백 제외 {len(re.sub(r'\s', '', nfc)):,}자",
        "- 원본: `본문/자기소개_본문.md` (사이트 이야기 칸과 자기소개서 본문에 그대로 쓰임)",
        "- 사실 기준: 리추얼 기록 원문, 9번 과제 서사 문서, 11번 소설의 사실 골격. 소설에서 각색된 대화·묘사와 동료 가명은 넣지 않음",
        "- 첫 문장은 본인이 직접 고쳐 씀",
        "",
        "---",
        "",
        전체,
    ])

    # 02 세 능력이 드러나는 장면 표시
    줄 = [
        "# 02. 세 능력이 드러나는 장면 표시",
        "",
        "이야기 본편의 몇 번째 토막(문단)에 어떤 날짜의 기록으로 드러나는지 표시했습니다.",
        "인용문은 모두 리추얼 기록 원문이며, `장치/승인문장/능력별_장면.json`에서 승인된 것만 씁니다.",
        "",
        "| 능력 | 날짜 · 칸 | 기록 원문 | 이야기 속 위치 |",
        "|---|---|---|---|",
    ]
    for 능력 in 능력순서:
        for s in [x for x in 장면들 if x["능력"] == 능력]:
            위치 = 인용_위치(s["인용"], 문단들)
            줄.append(f"| {능력} | {s['날짜']} · {s['칸']} | “{s['인용']}” | {위치} |")
    줄 += ["", "## 능력별 해석 (사이트 문구)", ""]
    for 능력 in 능력순서:
        줄.append(f"- **{능력}** — {메타['능력_해석'][능력]}")
    쓰기("02_세능력_장면표시.md", 줄)

    # 03 첫 화면
    쓰기("03_첫화면.md", [
        "# 03. 첫 화면",
        "",
        f"- 주소: {주소} (로그인·계정 없이 열림)",
        "- 스크린샷: `03_첫화면_PC.png` (1280×900, 배포 주소에서 캡처)",
        "",
        "## 구성",
        "",
        f"1. 이름 — **{메타['이름']}**",
        f"2. 한 줄 소개 — {메타['한줄소개']}",
        f"3. 한 줄 소개의 근거 — {메타['한줄소개_출처']}",
        "4. 입구 단추 — 이야기 · 세 가지 능력 · 숫자 · 대표작 · 과제 기록",
        "",
        "첫 화면 아래에 이야기(카드 1의 본편)가 바로 이어집니다.",
    ])

    # 04 한 줄 소개
    후보 = 읽기(본문폴더 / "한줄소개_후보.json")["후보"]
    줄 = ["# 04. 한 줄 소개", "", "카드 2번 첫 행동대로 세 가지를 쓰고 하나를 골랐습니다. 모두 날짜가 있는 장면을 \"…한 사람\" 앞에 두었습니다.", ""]
    for i, h in enumerate(후보, 1):
        표시 = " ✅ 선택" if h["선택"] else ""
        줄 += [f"## 후보 {i}{표시}", "", f"> {h['문구']}", "", f"- 근거: {h['근거']}", f"- 판단: {h['고른_이유']}", ""]
    선택 = next(h["문구"] for h in 후보 if h["선택"])
    일치 = "일치" if 선택 == 메타["한줄소개"] else "불일치 — 트랙 설정의 한줄소개를 확인하세요"
    줄.append(f"사이트에 실린 문구와 선택한 후보: **{일치}**")
    쓰기("04_한줄소개.md", 줄)

    # 05 날짜가 있는 장면으로 시작하는 이야기
    줄 = [
        "# 05. 날짜가 있는 장면으로 시작하는 이야기",
        "",
        "이야기는 날짜가 있는 장면(\"2022년 4월, …\")으로 시작합니다. 토막마다 첫머리에 날짜가 있는지 표시했습니다.",
        "",
        "| 토막 | 첫머리 | 날짜로 시작 |",
        "|---|---|---|",
    ]
    for i, p in enumerate(문단들, 1):
        첫머리 = p[:28].replace("|", "｜") + ("…" if len(p) > 28 else "")
        시작 = "O" if re.match(r"^(\d{4}년 )?\d{1,2}월( \d{1,2}일)?", p) else "—"
        줄.append(f"| {i} | {첫머리} | {시작} |")
    날짜토막 = sum(1 for p in 문단들 if re.match(r"^(\d{4}년 )?\d{1,2}월", p))
    줄 += ["", f"날짜로 시작하는 토막: {날짜토막} / {len(문단들)}", "", "---", "", "\n\n".join(문단들), "", 메타["마무리_목표문"]]
    쓰기("05_날짜장면으로_시작하는_이야기.md", 줄)

    # 06 숫자 칸
    줄 = ["# 06. 숫자 칸 (출처 포함)", "", "| 값 | 항목 | 보조 | 출처 |", "|---|---|---|---|"]
    for n in 숫자:
        줄.append(f"| {n['값']} | {n['이름']} | {n['보조'] or '—'} | {n['출처']} |")
    짝 = [n for n in 숫자 if n.get("짝")]
    if 짝:
        줄 += ["", "## 고난 장면과 짝지은 숫자", "", f"- **{짝[0]['이름']} ({짝[0]['값']})** — {짝[0]['짝']}"]
    줄 += ["", "숫자는 `python 장치/build.py`가 입력 파일에서 다시 셉니다. 원본 값은 `장치/마지막결과/숫자.json`."]
    쓰기("06_숫자칸_출처포함.md", 줄)

    # 07 대표작 자리
    줄 = ["# 07. 대표작 자리 (논문, 앱 예정)", ""]
    for w in 메타["대표작"]:
        줄 += [f"## {w['번호']} — {w['제목']}", "", f"- 상태: {w['상태']}", f"- 설명: {w['설명']}"]
        if w.get("링크"):
            링크 = w["링크"] if w["링크"].startswith("http") else f"{주소.rstrip('/')}/{w['링크']} (사이트에 파일을 직접 올려 로그인 없이 열림)"
            줄.append(f"- 링크: {링크}")
        줄.append("")
    쓰기("07_대표작자리.md", 줄)

    # 08~10 문서
    for 번호, 종류 in ((8, "이력서"), (9, "자기소개서"), (10, "경력기술서")):
        shutil.copyfile(사업장 / "문서" / f"{꼬리}_{종류}.md", 출력 / f"{번호:02d}_{종류}.md")
        print(f"[완료] 남길것/{번호:02d}_{종류}.md")
    docx = sorted((사업장 / "문서").glob("*.docx"))
    if docx:
        shutil.copyfile(docx[0], 출력 / f"08-10_{docx[0].name}")
        print(f"[완료] 남길것/08-10_{docx[0].name}")

    # 11 장치 ZIP
    zip경로 = 사업장 / "제출물" / "제출_문서와장치.zip"
    if zip경로.exists():
        shutil.copyfile(zip경로, 출력 / "11_장치ZIP_제출_문서와장치.zip")
        print("[완료] 남길것/11_장치ZIP_제출_문서와장치.zip")

    # 12 두 번 실행한 결과 비교
    재현 = 사업장 / "제출물" / "재현성_확인.md"
    if 재현.exists():
        shutil.copyfile(재현, 출력 / "12_두번실행_결과비교.md")
        print("[완료] 남길것/12_두번실행_결과비교.md")

    # 13 짧은 확인 방법 + AI와 나의 판단 세 줄
    확인 = (사업장 / "제출물" / "짧은_확인_방법.md").read_text(encoding="utf-8").split("\n", 1)[1].strip()
    쓰기("13_짧은확인방법_AI판단세줄.md", [
        "# 13. 짧은 확인 방법과 AI와 나의 판단 세 줄",
        "",
        "## AI와 나의 판단 세 줄",
        "",
        f"1. **AI에게 맡긴 일**: {판단['세줄']['AI에게_맡긴_일']}",
        f"2. **내가 직접 판단한 일**: {판단['세줄']['내가_직접_판단한_일']}",
        f"3. **AI 제안을 따르지 않은 일**: {판단['세줄']['AI_제안을_따르지_않은_일']}",
        "",
        "## 짧은 확인 방법",
        "",
        확인,
    ])

    # 00 목차
    쓰기("00_목차.md", [
        "# 과제 A(12번) 남길 것 · 제출물 목차",
        "",
        "## 제출물",
        "",
        "| 제출 칸 | 낼 것 |",
        "|---|---|",
        f"| 1. 결과물 URL | {주소} |",
        f"| 2. 문서 파일 | `08-10_{docx[0].name if docx else '(docx 없음)'}` |",
        "| 3. 장치 ZIP | `11_장치ZIP_제출_문서와장치.zip` (문서 MD·장치·본문·확인 방법·제출문·재현성 기록 포함) |",
        "| 4. 짧은 확인 방법 + AI와 나의 판단 세 줄 | `13_짧은확인방법_AI판단세줄.md` |",
        "",
        "## 필요 자료 (과제 카드별 남길 것)",
        "",
        "| 번호 | 자료 | 카드 | 파일 |",
        "|---|---|---|---|",
        "| 1 | 자기소개 본편 1,500자 안팎 | 1 | `01_자기소개_본편.md` |",
        "| 2 | 세 능력이 드러나는 장면 표시 | 1 | `02_세능력_장면표시.md` |",
        "| 3 | 첫 화면 | 2 | `03_첫화면.md`, `03_첫화면_PC.png` |",
        "| 4 | 한 줄 소개 | 2 | `04_한줄소개.md` |",
        "| 5 | 날짜가 있는 장면으로 시작하는 이야기 | 2 | `05_날짜장면으로_시작하는_이야기.md` |",
        "| 6 | 숫자 칸(출처 포함) | 3 | `06_숫자칸_출처포함.md` |",
        "| 7 | 대표작 자리(논문, 앱 예정) | 3 | `07_대표작자리.md` |",
        "| 8 | 이력서 | 4 | `08_이력서.md` |",
        "| 9 | 자기소개서 | 4 | `09_자기소개서.md` |",
        "| 10 | 경력기술서 | 4 | `10_경력기술서.md` |",
        "| 11 | 장치 ZIP(실행 소스·README·마지막 결과) | 5 | `11_장치ZIP_제출_문서와장치.zip` |",
        "| — | 두 번 실행한 결과 비교 | 5 | `12_두번실행_결과비교.md` |",
        "| — | 짧은 확인 방법과 AI와 나의 판단 세 줄 | 5 | `13_짧은확인방법_AI판단세줄.md` |",
        "",
        f"사이트 원본: `{사이트폴더}/index.html` · 다시 만들기: `python 장치/build.py` → `node 장치/문서_docx.js` → `python 장치/묶기.py` → `python 장치/남길것.py`",
    ])


if __name__ == "__main__":
    만들기()
